"""Draw the tackle-shop keeper and pack the opaque RGB565 spans. Requires Pillow."""
from itertools import groupby
from pathlib import Path

from PIL import Image, ImageDraw

from paint_bay_fish import packed_color

image = Image.new("RGB", (50, 52))
draw = ImageDraw.Draw(image)
ink = "#25323a"
flannel = "#8f4b46"
skin = "#cf9b77"
skin_light = "#e5b68a"
skin_shadow = "#9b5f49"
beard = "#59483d"

def poly(points, color, outline=None):
    draw.polygon(points, fill=color, outline=outline)

# Flannel plaid follows a broad shoulder shape. The pale cuffs expose both forearms.
shirt = [(3,51),(3,44),(8,39),(17,36),(22,35),(30,35),(35,37),(43,39),(47,43),(48,51)]
poly(shirt, flannel, ink)
plaid = Image.new("RGB", image.size)
stripes = ImageDraw.Draw(plaid)
for x in (5, 13, 21, 29, 37, 45):
    stripes.rectangle((x,36,x+2,51),fill="#62393b")
    stripes.line((x+3,36,x+3,51),fill="#af6052")
for y in (39, 45, 50):
    stripes.rectangle((3,y,48,y+1),fill="#6c3e43")
    stripes.line((3,y+2,48,y+2),fill="#b76554")
for y in range(36,52):
    for x in range(3,49):
        color = plaid.getpixel((x,y))
        if color != (0,0,0) and image.getpixel((x,y)) == (143,75,70):
            image.putpixel((x,y),color)
poly([(3,46),(10,43),(13,46),(12,48),(3,50)], "#ba8370", ink)
poly([(3,50),(12,47),(15,49),(14,51),(2,51)], skin_shadow)
draw.line((4,49,10,48),fill=skin)
poly([(39,46),(46,44),(48,47),(46,49),(40,49)], "#c2967c", ink)
poly([(40,49),(47,47),(49,49),(49,51),(38,51)], skin)
draw.line((42,49,47,48),fill=skin_light)
draw.line((26,40,26,51),fill="#50383a")
draw.point((27,46),fill="#dcc0a6")
draw.point((27,50),fill="#dcc0a6")

# Facial silhouette, warm window light, and full dark beard.
poly([(19,30),(31,30),(33,39),(27,44),(21,42),(17,37)],skin_shadow,ink)
poly([(11,13),(15,8),(29,7),(36,11),(40,17),(41,27),(37,34),(33,40),(23,41),
      (15,37),(11,30),(8,26),(8,21),(11,19)],skin,ink)
poly([(31,11),(36,14),(39,21),(38,28),(35,32),(28,32),(27,28),(31,23)],skin_light)
poly([(12,20),(14,21),(15,28),(17,30),(20,29),(22,27),(29,28),(34,27),(37,24),
      (39,28),(37,35),(33,40),(27,42),(20,41),(15,38),(12,33),(10,28)],beard)
poly([(31,31),(35,30),(37,33),(34,37),(28,39),(24,38)],"#6f5647")
draw.line([(15,34),(18,38),(23,40)],fill="#3f3a35")
draw.line([(18,34),(21,37),(25,38)],fill="#846554")
draw.line([(28,39),(32,38),(34,36)],fill="#a17b62")
draw.line([(26,22),(26,25),(28,27),(25,27)],fill=skin_shadow)
poly([(19,30),(22,29),(28,30),(34,28),(34,31),(30,34),(24,35),(20,33)],
     "#492f2e")
draw.line([(21,31),(25,32),(30,31),(33,30)],fill="#f1d5ad")
draw.line((24,34,29,33),fill="#bd7960")

# Black rectangular frames, with the eye and a pixel of reflection in each lens.
draw.line((9,18,15,20),fill=ink,width=2)
draw.rounded_rectangle((13,18,25,26),radius=2,outline=ink,width=2)
draw.rounded_rectangle((27,19,40,27),radius=2,outline=ink,width=2)
draw.line((24,21,28,21),fill=ink,width=2)
draw.point((20,22),fill=ink)
draw.point((33,23),fill=ink)
draw.line((16,20,19,20),fill="#ebbe97")
draw.point((31,21),fill="#f1d2ad")

# Backward trucker hat. The small bill sits at the nape, away from the window.
poly([(9,16),(10,8),(15,4),(21,2),(30,2),(36,5),(39,10),(40,15),(39,17),
      (31,14),(22,13),(15,15),(11,18)],"#32343e",ink)
poly([(11,9),(16,6),(20,5),(19,13),(13,15),(10,16)],"#565660")
for x,y in ((13,10),(15,9),(16,11),(13,13),(17,8)):
    draw.point((x,y),fill="#77727a")
draw.line([(20,4),(26,3),(32,4),(35,6)],fill="#66616c")
poly([(5,17),(10,15),(15,14),(17,16),(12,19),(5,20),(2,19)],"#282c36",ink)
draw.line([(13,16),(18,14),(22,14)],fill="#72707b")

spans = []
for y in range(image.height):
    x = 0
    for color, group in groupby(image.getpixel((i, y)) for i in range(image.width)):
        length = len(list(group))
        if color != (0, 0, 0):
            spans.append(f"{{{x},{y},{length},0x{packed_color(color):04x}}},")
        x += length

header = ["#pragma once", "", "// Generated by tools/bobber/paint_shopkeeper.py.",
          '#include "bobber_bay_portraits.h"', "",
          "static const BobberPortraitSpan bobberShopkeeper[] = {"]
header += ["  " + " ".join(spans[i:i+5]) for i in range(0, len(spans), 5)]
header += ["};", ""]
(Path(__file__).resolve().parents[2] / "bobber_shopkeeper_art.h").write_text("\n".join(header))

def perch(m, rng, ink, back):
    for x in (33,43,54,65,75):
        m.polygon([(x,9),(x+4,9),(x+9,30),(x+5,31)], fill="#525834")

def pumpkinseed(m, rng, ink, back):
    for x in range(26,71,5):
        for y in range(16+x%3,34,5):
            m.line((x,y,x+2,y-1), fill="#dc9a48" if x%2 else "#588b80")
    m.ellipse((33,18,42,25), fill=ink)
    m.rectangle((40,21,43,24), fill="#d0633e")
    m.line([(19,23),(25,21),(30,22)], fill="#6aa9a0")

def brook(m, rng, ink, back):
    for x in range(34,82,7):
        y = rng.randrange(13,18)
        m.line([(x,y),(x+2,y-1),(x+3,y+1),(x+5,y+2)], fill="#b3b077")
    for x,y in [(34,24),(44,25),(53,20),(58,27),(65,24),(75,23)]:
        m.rectangle((x-1,y-1,x+1,y+1), fill="#9aaa9e")
        m.point((x,y), fill="#d25f46")
    m.line((28,33,53,36), fill="#f2e4be", width=2)

def largemouth(m, rng, ink, back):
    m.line([(9,26),(16,25),(30,27)], fill=ink, width=2)
    m.line([(32,24),(44,25),(58,23),(70,24),(86,24)], fill="#475b3e", width=4)
    for x in range(38,82,8):
        m.line((x,21,x+3,25), fill="#596944", width=2)

def trout(m, rng, ink, back, kind):
    if kind == "rainbow":
        m.line([(26,24),(43,23),(65,24),(90,24)],fill="#bd8589",width=4)
    pale = kind == "lake"
    for i in range(38 if pale else 31):
        x, y = rng.randrange(31,103), rng.randrange(11,29 if pale else 25)
        if kind == "brown" and i % 3 == 0:
            m.rectangle((x-1,y-1,x+1,y+1),fill="#dfbd83")
            m.point((x,y),fill="#a7483a")
        else:
            m.line((x,y,x+(i%3==0),y),fill="#c5c6a2" if pale else "#4b5350")

def muskie(m, rng, ink, back):
    for x in range(32,89,8):
        m.line([(x,14),(x+2,20),(x+4,25)], fill="#53665a", width=2)
    m.line((5,25,22,25),fill=ink)

def leviathan(m, rng, ink, back):
    # Tall dorsal scutes and a dotted row of armor along the flank.
    for x,y in [(28,15),(36,12),(45,11),(54,13),(63,15),(72,18),(81,21)]:
        m.polygon([(x-2,y+4),(x,y),(x+3,y+4),(x+1,y+6)], fill="#b4c5b2")
    for x,y in [(33,24),(43,23),(53,24),(63,25),(73,26),(83,26)]:
        m.polygon([(x-2,y),(x,y-2),(x+3,y),(x,y+2)], fill="#aabbb2")
    m.line([(8,28),(20,26),(27,25)],fill="#91aba7")


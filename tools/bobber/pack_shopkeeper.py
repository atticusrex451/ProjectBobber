"""Pack the transparent 1× shopkeeper sprite for firmware. Requires Pillow."""
from pathlib import Path
from itertools import groupby

from PIL import Image

from paint_bay_fish import packed_color

source = Path(__file__).with_name("shopkeeper.png")
output = source.resolve().parents[2] / "bobber_shopkeeper_art.h"
with Image.open(source) as asset:
    image = asset.convert("RGBA")
if not (1 <= image.width <= 110 and 1 <= image.height <= 95):
    raise ValueError("Shopkeeper sprite must fit within 110 × 95 source pixels")

spans = []
for y in range(image.height):
    x = 0
    # Group transparent pixels together so the shop painting shows through.
    row = [packed_color(pixel[:3]) if pixel[3] >= 128 else None
           for pixel in (image.getpixel((x, y)) for x in range(image.width))]
    for color, group in groupby(row):
        length = len(list(group))
        if color is not None:
            spans.append(f"{{{x},{y},{length},0x{color:04x}}},")
        x += length

header = ["#pragma once", "", "// Generated by tools/bobber/pack_shopkeeper.py.",
          '#include "bobber_bay_portraits.h"', "",
          f"static constexpr int BOBBER_SHOPKEEPER_WIDTH = {image.width};",
          f"static constexpr int BOBBER_SHOPKEEPER_HEIGHT = {image.height};",
          "static const BobberPortraitSpan bobberShopkeeper[] = {"]
header += ["  " + " ".join(spans[i:i+5]) for i in range(0, len(spans), 5)]
header += ["};", ""]
output.write_text("\n".join(header))

"""Pack the three aligned transparent shopkeeper poses for firmware. Requires Pillow."""
from itertools import groupby
from pathlib import Path

from PIL import Image

from paint_bay_fish import packed_color

folder = Path(__file__).resolve().parent
output = folder.parents[1] / "bobber_shopkeeper_art.h"
poses = {
    "Rest": "shopkeeper-rest.png",
    "Lift": "shopkeeper-lift.png",
    "ThumbsUp": "shopkeeper.png",
}
images = {}
for pose, filename in poses.items():
    with Image.open(folder / filename) as asset:
        images[pose] = asset.convert("RGBA")
width, height = images["ThumbsUp"].size
if not (1 <= width <= 110 and 1 <= height <= 95):
    raise ValueError("Shopkeeper sprites must fit within 110 × 95 source pixels")

header = ["#pragma once", "", "// Generated by tools/bobber/pack_shopkeeper.py.",
          '#include "bobber_bay_portraits.h"', "",
          f"static constexpr int BOBBER_SHOPKEEPER_WIDTH = {width};",
          f"static constexpr int BOBBER_SHOPKEEPER_HEIGHT = {height};"]
for pose, image in images.items():
    if image.size != (width, height):
        raise ValueError(f"{pose} must match the thumbs-up canvas")
shared_rows = 0
for y in range(height):
    rows = {image.crop((0, y, width, y + 1)).tobytes() for image in images.values()}
    if len(rows) != 1:
        break
    shared_rows += 1

def emit(pose, image, top, bottom):
    spans = []
    for y in range(top, bottom):
        x = 0
        # Skip transparent runs so that the painting shows through.
        row = [packed_color(pixel[:3]) if pixel[3] >= 128 else None
               for pixel in (image.getpixel((x, y)) for x in range(width))]
        for color, group in groupby(row):
            length = len(list(group))
            if color is not None:
                spans.append(f"{{{x},{y},{length},0x{color:04x}}},")
            x += length
    header.extend(["", f"static const BobberPortraitSpan bobberShopkeeper{pose}[] = {{"])
    header.extend("  " + " ".join(spans[i:i+5]) for i in range(0, len(spans), 5))
    header.append("};")
emit("Head", images["ThumbsUp"], 0, shared_rows)
for pose, image in images.items():
    emit(pose, image, shared_rows, height)

header += ["", "struct BobberShopkeeperPose { const BobberPortraitSpan *spans; size_t count; };",
           "static constexpr BobberShopkeeperPose bobberShopkeeperPoses[] = {"]
for pose in poses:
    name = f"bobberShopkeeper{pose}"
    header.append(f"  {{{name}, sizeof({name}) / sizeof({name}[0])}},")
header += ["};", ""]
output.write_text("\n".join(header))
